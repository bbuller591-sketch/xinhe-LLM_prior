X=np.load(ROOT/'canonical/X_candidate_aligned_log1p.npy').astype(float)
y=pd.read_csv(ROOT/'canonical/y_canonical.csv')['y'].to_numpy(int)
mp=pd.read_csv(ROOT/'canonical/cell_sample_mapping_canonical.csv')
